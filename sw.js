const CACHE_NAME = "athar-cache-v3";
const QCF_CACHE = "wirdi-qcf";   // mushaf page fonts: kept across app updates, so pages read once work offline
const APP_SHELL = ["./", "./index.html", "./manifest.json", "./icon-192.png", "./icon-512.png", "./badge-96.png", "./fonts/UthmanicHafs.woff2"];

self.addEventListener("install", function(event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function(cache) {
      return cache.addAll(APP_SHELL);
    })
  );
  self.skipWaiting();
});

self.addEventListener("activate", function(event) {
  event.waitUntil(
    caches.keys().then(function(keys) {
      return Promise.all(
        keys.filter(function(key) { return key.indexOf("athar-") === 0 && key !== CACHE_NAME && key.indexOf("athar-audio") !== 0 && key.indexOf("athar-tafsir") !== 0 && key !== "athar-meta" && key !== QCF_CACHE; }).map(function(key) { return caches.delete(key); })
      );
    })
  );
  self.clients.claim();
});

